def _room_tiles():
    import simple_control as sc
    out = {}
    for room in sc.ROOM_ORDER:
        for t in sc.ROOM_TILES[room]:
            if t[6]:                      # 场景格：卡片只展示，「执行」进场景页
                out[(room, "%s·执行" % t[0])] = "场景详情"
                continue
            if t[0] == "空调":
                page = "空调详情"
            elif t[0] == "摄像头":
                page = "摄像头详情"
            elif t[0] == "插座":
                page = "插座详情"
            elif t[0] in ("窗帘",):
                page = "窗帘详情"
            elif t[5] or t[0] in ("温湿度", "燃气传感", "漏水传感"):
                page = "传感详情"
            else:
                page = "灯详情"
            out[(room, "%s·详情" % t[0])] = page
    return out


